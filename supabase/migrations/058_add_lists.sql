-- Listes thématiques partageables (retour utilisateur, étude comparative
-- Letterboxd : "Movies everyone should watch at least once", collections
-- créées par les utilisateurs, likeables) — le plus gros écart structurel
-- identifié : watchlist est privée, Top films est algorithmique, Groupes
-- est un cercle fermé, rien ne permettait de composer et partager une
-- collection thématique. Adapté à l'esprit fermé de Kinet (pas un vrai
-- public internet comme Letterboxd) : visible entre amis seulement, même
-- restriction que film_likes/film_comments (migrations/030) via
-- are_friends(), jamais un lien public anonyme.
--
-- list_items dénormalise tmdb_id/title/poster_url/release_year (comme
-- watchlist, migrations/006) plutôt que de référencer `films` : un film
-- d'une liste n'a pas besoin d'être déjà noté/suivi par son auteur. user_id
-- y est AUSSI dénormalisé (copie du propriétaire de la liste parente) pour
-- que les policies RLS restent de simples comparaisons are_friends(),
-- sans sous-requête — même raisonnement que activity_events dénormalisant
-- déjà le titre (migrations/019).

create table public.lists (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  description text,
  created_at timestamptz not null default now()
);

create table public.list_items (
  id bigint generated by default as identity primary key,
  list_id bigint not null references public.lists(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  tmdb_id integer not null,
  title text not null,
  poster_url text,
  release_year integer,
  position integer not null default 0,
  added_at timestamptz not null default now()
);

create table public.list_likes (
  id bigint generated by default as identity primary key,
  list_id bigint not null references public.lists(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (list_id, user_id)
);

alter table public.lists enable row level security;
alter table public.list_items enable row level security;
alter table public.list_likes enable row level security;

-- are_friends(x, x) = true (voir migrations/030) : une seule policy select
-- couvre à la fois "mes propres listes" et "celles de mes amis".
create policy "Users can view own or friends' lists"
  on public.lists for select
  using (public.are_friends(auth.uid(), user_id));

create policy "Users can create own lists"
  on public.lists for insert
  with check (auth.uid() = user_id);

create policy "Users can update own lists"
  on public.lists for update
  using (auth.uid() = user_id);

create policy "Users can delete own lists"
  on public.lists for delete
  using (auth.uid() = user_id);

create policy "Users can view items of visible lists"
  on public.list_items for select
  using (public.are_friends(auth.uid(), user_id));

-- La double condition (user_id ET list_id réellement possédé par ce même
-- user_id) empêche un client buggé/malveillant d'insérer un item avec
-- user_id = soi-même mais list_id d'une liste appartenant à quelqu'un
-- d'autre — jamais juste "fais confiance à ce que le client envoie".
create policy "Users can add items to own lists"
  on public.list_items for insert
  with check (
    auth.uid() = user_id
    and exists (select 1 from public.lists l where l.id = list_id and l.user_id = auth.uid())
  );

create policy "Users can remove items from own lists"
  on public.list_items for delete
  using (auth.uid() = user_id);

create policy "Users can view likes on visible lists"
  on public.list_likes for select
  using (exists (
    select 1 from public.lists l where l.id = list_id and public.are_friends(auth.uid(), l.user_id)
  ));

create policy "Users can like a visible list as themselves"
  on public.list_likes for insert
  with check (
    auth.uid() = user_id
    and exists (select 1 from public.lists l where l.id = list_id and public.are_friends(auth.uid(), l.user_id))
  );

create policy "Users can unlike their own like"
  on public.list_likes for delete
  using (auth.uid() = user_id);

-- Flux "Listes de mes amis" (page d'index, js/lists.js) : jamais mes
-- propres listes (déjà affichées séparément), triées des plus récentes aux
-- plus anciennes. poster_urls = jusqu'à 4 affiches de couverture (même
-- esprit que le mur de posters du profil public, migrations/016), pas un
-- aperçu complet du contenu.
create or replace function public.get_friends_lists()
returns table(
  id bigint,
  user_id uuid,
  title text,
  description text,
  created_at timestamptz,
  item_count integer,
  like_count integer,
  poster_urls text[]
)
language sql
security definer
set search_path = public
stable
as $func$
  select
    l.id, l.user_id, l.title, l.description, l.created_at,
    (select count(*)::integer from public.list_items li where li.list_id = l.id) as item_count,
    (select count(*)::integer from public.list_likes lk where lk.list_id = l.id) as like_count,
    (select array_agg(sub.poster_url) from (
      select li2.poster_url from public.list_items li2
      where li2.list_id = l.id and li2.poster_url is not null
      order by li2.position
      limit 4
    ) sub) as poster_urls
  from public.lists l
  where l.user_id <> auth.uid()
    and public.are_friends(auth.uid(), l.user_id)
  order by l.created_at desc;
$func$;

revoke all on function public.get_friends_lists() from public;
grant execute on function public.get_friends_lists() to authenticated;
